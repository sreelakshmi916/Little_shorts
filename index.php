<h2>What is Little Shorts?</h2>

<p>
	Babies need different vaccines at different stages of their growth.
	Keeping track of vaccinations can sometimes be difficult.
	Little Shorts is a Baby Vaccination Tracking System that helps parents
	manage their baby's details, view important vaccine information, and
	maintain vaccination records.
</p>

<h2>Why is Vaccination Important for Your Baby?</h2>

<p>
	Vaccination helps protect babies from several serious diseases.
	Vaccines help the body's immune system learn how to fight certain infections.
	Following the recommended vaccination schedule helps parents keep track
	of important vaccinations during their baby's growth.
</p>

